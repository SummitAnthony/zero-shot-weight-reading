#!/usr/bin/env python3
"""
$5 API pilot: the go/no-go gate for "Circuits, Execution or Statistics?"

Runs the Pilot 2 networks (505 and 2,997 weights; originals vs output-sign flips)
through the Claude API with CAPPED output, and answers three questions:
  1. Does Sonnet still name ~3,000-weight originals correctly (>= 60%)?
  2. Is the catch rate on broken networks clearly lower than on originals?
  3. Do output lengths fit the budget?

Hard spending cap: before every call the script reserves the WORST-CASE cost
(input tokens + max_tokens of output) and refuses the call if that could push
total spend past BUDGET_USD. Actual cost from the API's usage numbers is then
settled. Also set a spend limit in the Claude Console as a second safety net.

Usage:
  pip install anthropic
  export ANTHROPIC_API_KEY=sk-ant-...        (Windows PowerShell: $env:ANTHROPIC_API_KEY="sk-ant-...")
  python pilot_api.py --dry-run              # free: builds prompts, counts nothing, shows the plan
  python pilot_api.py --count-only           # free: measures real tokens per weight with count_tokens
  python pilot_api.py                        # runs the pilot (resumable; rerun to continue)
  python pilot_api.py --report               # re-prints the analysis from results.jsonl
"""
import argparse, json, os, re, sys, time, threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

# ---------------- configuration ----------------
BUDGET_USD = 6.00            # hard cap for this script, total across all rounds (round 1 spent about $2.70; round 2 needs headroom because every call reserves its worst case)
WORKERS = 4                  # parallel requests
HERE = Path(__file__).resolve().parent
NETS = HERE / "networks"
RESULTS = HERE / "results.jsonl"

MODELS = {"haiku": "claude-haiku-5-5", "sonnet": "claude-sonnet-5-5", "opus": "claude-opus-5-5"}
# Standard (non-batch) prices, USD per million tokens, checked 2026-11-04 at
# https://platform.claude.com/docs/en/about-claude/pricing . Haiku prompts here stay under 100k tokens.
PRICE = {"haiku": (0.10, 0.50), "sonnet": (2.00, 10.00), "opus": (4.00, 20.00)}

SYSTEM = "You are a careful analyst. Answer the question about the network you are given."
ANSWER_INSTRUCTION = ("\n\nWork it out from the weights. Do not write or run code. "
                      "End your reply with one final line exactly in this form: ANSWER: <one letter from A to I>")

# Runs in priority order. If the budget runs short, later runs are skipped.
#   name, model, effort, max_tokens, which stimuli, samples per stimulus
#   optional 7th field: thinking setting (None = adaptive, the default)
RUNS = [
    # Round 1 (already run)
    ("sonnet_medium_6k", "sonnet", "medium", 6000, "all", 1),    # main gate test, capped
    ("haiku_high_6k_x2", "haiku", "high", 6000, "all", 2),       # cheap; 2 samples = test-retest
    ("sonnet_high_16k_big", "sonnet", "high", 16000, "big_set0", 1),  # does a looser cap help on big nets?
    # Round 2: 16 NEW ~3,000-weight networks, each shown as original and as broken (generated by make_extra.py)
    ("sonnet_medium_6k_extra", "sonnet", "medium", 6000, "extra", 1),  # identical settings to round 1's main run
    ("haiku_nothink_big", "haiku", "low", 1500, "big_and_extra", 1, {"type": "disabled"}),  # pure "glance" reader
]
ROUND2 = {"sonnet_medium_6k_extra", "haiku_nothink_big"}
# Opus is left out of the $5 pilot (about $0.17+ per large call). Add e.g.
# ("opus_medium_8k_big", "opus", "medium", 8000, "big_set0", 1) if you raise BUDGET_USD.

# ---------------- stimuli ----------------
def load_stimuli():
    key = json.loads((NETS / "answer_key.json").read_text())
    stim = []
    for H, nw in [(36, 505), (214, 2997)]:
        for st in (0, 1):
            text = (NETS / f"prompt_H{H}_set{st}.txt").read_text()
            head, *blocks = re.split(r"(?=### Network S\d+)", text)
            head = head.replace("Networks are independent; any option may appear any number of times, including I. ",
                                "Any option may be correct, including I. ")
            head = head.replace("For EACH network, decide", "Decide")
            head = head.replace("Each network below is", "The network below is")
            for b in blocks:
                sid = re.match(r"### Network (S\d+)", b).group(1)
                k = key[f"H{H}_set{st}_{sid}"]
                body = re.sub(r"### Network S\d+", "### Network", b, count=1)
                stim.append(dict(id=f"H{H}_set{st}_{sid}", H=H, nweights=nw, set=st,
                                 func=k["func"], version=k["version"], label=k["label"],
                                 prompt=head.rstrip() + "\n\n" + body.strip() + ANSWER_INSTRUCTION))
    # round-2 networks
    xp, xk = HERE / "extra" / "prompt_extra.txt", HERE / "extra" / "answer_key.json"
    if xp.exists():
        key = json.loads(xk.read_text())
        head, *blocks = re.split(r"(?=### Network S\d+)", xp.read_text())
        head = head.replace("Networks are independent; any option may appear any number of times, including I. ",
                            "Any option may be correct, including I. ")
        head = head.replace("For EACH network, decide", "Decide").replace("Each network below is", "The network below is")
        for b in blocks:
            sid = re.match(r"### Network (S\d+)", b).group(1); k = key[f"X_{sid}"]
            body = re.sub(r"### Network S\d+", "### Network", b, count=1)
            stim.append(dict(id=f"X_{sid}", H=214, nweights=2997, set="extra", network=k["network"],
                             func=k["func"], version=k["version"], label=k["label"],
                             prompt=head.rstrip() + "\n\n" + body.strip() + ANSWER_INSTRUCTION))
    for s in stim: s.setdefault("network", f"{s['func']}_H{s['H']}")   # round-1 pairs: same function and size = same network
    return stim

def select(stim, which):
    if which == "all": return [s for s in stim if s["set"] != "extra"]
    if which == "big_set0": return [s for s in stim if s["H"] == 214 and s["set"] == 0]  # 4 originals + 4 flips
    if which == "extra": return [s for s in stim if s["set"] == "extra"]
    if which == "big_and_extra": return [s for s in stim if s["H"] == 214]
    raise ValueError(which)

# ---------------- budget guard ----------------
class Budget:
    def __init__(self, cap, spent):
        self.cap, self.spent, self.reserved, self.lock = cap, spent, 0.0, threading.Lock()
    def reserve(self, amount):
        with self.lock:
            if self.spent + self.reserved + amount > self.cap: return False
            self.reserved += amount; return True
    def settle(self, reserved, actual):
        with self.lock:
            self.reserved -= reserved; self.spent += actual

def cost(model, tin, tout):
    pi, po = PRICE[model]; return (tin * pi + tout * po) / 1e6

def est_tokens(text):      # conservative fallback when count_tokens isn't used: ~0.75 tokens per character for number-heavy text
    return int(len(text) * 0.75) + 50

# ---------------- API ----------------
def make_client():
    try:
        import anthropic
    except ImportError:
        sys.exit("Install the SDK first:  pip install anthropic")
    if not os.environ.get("ANTHROPIC_API_KEY"):
        sys.exit("Set ANTHROPIC_API_KEY first.")
    return anthropic.Anthropic(max_retries=5, timeout=900)

def call(client, model, effort, max_tokens, prompt, thinking=None):
    t0 = time.time()
    body = {"output_config": {"effort": effort}}   # adaptive thinking is the default on 5.5 models
    if thinking: body["thinking"] = thinking        # e.g. {"type": "disabled"} (Haiku 5.5, effort high or below)
    r = client.messages.create(
        model=MODELS[model], max_tokens=max_tokens, system=SYSTEM,
        messages=[{"role": "user", "content": prompt}], extra_body=body,
    )
    text = "".join(b.text for b in r.content if getattr(b, "type", "") == "text")
    m = re.findall(r"ANSWER:\s*\**\s*([A-I])\b", text)
    return dict(answer=m[-1] if m else None, stop_reason=r.stop_reason, model_id=r.model,
                input_tokens=r.usage.input_tokens, output_tokens=r.usage.output_tokens,
                seconds=round(time.time() - t0, 1), text_tail=text[-600:])

# ---------------- main ----------------
def done_keys():
    if not RESULTS.exists(): return set(), 0.0
    keys, spent = set(), 0.0
    for line in RESULTS.read_text().splitlines():
        r = json.loads(line); keys.add((r["run"], r["id"], r["sample"])); spent += r["cost"]
    return keys, spent

def plan(stim):
    jobs = []
    for name, model, effort, mt, which, n, *th in RUNS:
        for s in select(stim, which):
            for k in range(n): jobs.append((name, model, effort, mt, s, k, th[0] if th else None))
    return jobs

def run(args):
    stim = load_stimuli(); jobs = plan(stim)
    done, spent = done_keys()
    todo = [j for j in jobs if (j[0], j[4]["id"], j[5]) not in done]
    if args.round2_only: todo = [j for j in todo if j[0] in ROUND2]
    worst = sum(cost(j[1], est_tokens(j[4]["prompt"]), j[3]) for j in jobs)
    print(f"{len(jobs)} calls planned, {len(todo)} to go. Already spent ${spent:.2f}. "
          f"Worst case for all calls ${worst:.2f}; cap ${BUDGET_USD:.2f}.")
    if args.dry_run:
        for name, model, effort, mt, which, n, *th in RUNS:
            sel = select(stim, which)
            w = sum(cost(model, est_tokens(s["prompt"]), mt) for s in sel) * n
            print(f"  {name:22s} {len(sel)*n:3d} calls  worst case ${w:.2f}")
        print("Dry run only. Nothing was sent."); return
    client = make_client(); budget = Budget(BUDGET_USD, spent); lock = threading.Lock(); skipped = 0

    def work(job):
        name, model, effort, mt, s, k, th = job
        res_worst = cost(model, est_tokens(s["prompt"]), mt)
        if not budget.reserve(res_worst): return "skipped"
        try:
            r = call(client, model, effort, mt, s["prompt"], th)
        except Exception as e:
            budget.settle(res_worst, 0.0); return f"error: {e}"
        c = cost(model, r["input_tokens"], r["output_tokens"]); budget.settle(res_worst, c)
        row = dict(run=name, model=model, effort=effort, max_tokens=mt, thinking=th, network=s["network"], id=s["id"], sample=k,
                   H=s["H"], nweights=s["nweights"], func=s["func"], version=s["version"], label=s["label"],
                   correct=r["answer"] == s["label"], named_original=(s["version"] == "flip" and r["answer"] == s["func"]),
                   cost=round(c, 5), **r)
        with lock:
            with RESULTS.open("a") as f: f.write(json.dumps(row) + "\n")
        return f"{name} {s['id']} {s['version']}: {r['answer']} (truth {s['label']}) out={r['output_tokens']} " \
               f"{r['stop_reason']} ${c:.3f} | total ${budget.spent:.2f}"

    with ThreadPoolExecutor(WORKERS) as ex:
        for fut in as_completed([ex.submit(work, j) for j in todo]):
            msg = fut.result()
            if msg == "skipped": skipped += 1
            else: print(msg, flush=True)
    if skipped: print(f"{skipped} calls skipped to stay under the ${BUDGET_USD:.2f} cap.")
    report()

def count_only():
    client = make_client(); stim = load_stimuli()
    for H in (36, 214):
        s = next(x for x in stim if x["H"] == H)
        for m in ("haiku", "sonnet"):
            n = client.messages.count_tokens(model=MODELS[m], system=SYSTEM,
                                             messages=[{"role": "user", "content": s["prompt"]}]).input_tokens
            base = client.messages.count_tokens(model=MODELS[m], system=SYSTEM,
                                                messages=[{"role": "user", "content": s["prompt"].split("### Network")[0]}]).input_tokens
            print(f"{m:6s} {s['nweights']:5d} weights: {n} input tokens, {(n-base)/s['nweights']:.2f} tokens per weight")

def report():
    if not RESULTS.exists(): print("No results yet."); return
    rows = [json.loads(l) for l in RESULTS.read_text().splitlines()]
    spent = sum(r["cost"] for r in rows)
    print(f"\n=== Results ({len(rows)} calls, ${spent:.2f} spent) ===")
    from collections import defaultdict
    g = defaultdict(list)
    for r in rows: g[(r["run"], r["nweights"], r["version"])].append(r)
    print(f"{'run':22s} {'weights':>7s} {'version':8s} {'correct':>9s} {'named old':>9s} {'truncated':>9s} {'mean out':>8s} {'max out':>7s}")
    for (run, nw, v), rs in sorted(g.items()):
        n = len(rs); c = sum(r["correct"] for r in rs); no = sum(r["named_original"] for r in rs)
        tr = sum(r["stop_reason"] == "max_tokens" or r["answer"] is None for r in rs)
        outs = [r["output_tokens"] for r in rs]
        print(f"{run:22s} {nw:7d} {v:8s} {c:4d}/{n:<4d} {no if v=='flip' else '-':>9} {tr:9d} {sum(outs)/n:8.0f} {max(outs):7d}")
    # test-retest (Haiku, 2 samples)
    by = defaultdict(dict)
    for r in rows:
        if r["run"] == "haiku_high_6k_x2": by[r["id"]][r["sample"]] = r["answer"]
    pairs = [v for v in by.values() if len(v) == 2 and v[0] is not None and v[1] is not None]
    print(f"\nHaiku test-retest: {len(pairs)} pairs with two real answers" +
          (f", disagreement {sum(v[0] != v[1] for v in pairs) / len(pairs):.0%} (power analysis assumed <= 20%)" if pairs
           else " (not measurable; truncated answers are excluded)"))
    # gate
    main = [r for r in rows if r["run"] == "sonnet_medium_6k" and r["nweights"] == 2997]
    if main:
        o = [r for r in main if r["version"] == "orig"]; f = [r for r in main if r["version"] == "flip"]
        acc_o = sum(r["correct"] for r in o) / max(1, len(o)); acc_f = sum(r["correct"] for r in f) / max(1, len(f))
        out_big = sum(r["output_tokens"] for r in main) / len(main)
        trunc = sum(r["stop_reason"] == "max_tokens" or r["answer"] is None for r in main) / len(main)
        print("\n=== GO / NO-GO (Sonnet, capped at 6,000 output tokens, ~3,000-weight networks) ===")
        print(f"1. Originals correct: {acc_o:.0%} (need >= 60%)  -> {'PASS' if acc_o >= 0.6 else 'FAIL'}")
        print(f"2. Broken caught: {acc_f:.0%}, gap {acc_o-acc_f:+.0%} (need a clear gap, ~30 points) -> "
              f"{'PASS' if acc_o - acc_f >= 0.3 else 'CHECK'}")
        print(f"3. Mean output {out_big:.0f} tokens, {trunc:.0%} truncated (budget plan assumed ~4,000, few truncations) -> "
              f"{'PASS' if out_big <= 5000 and trunc <= 0.2 else 'CHECK'}")
        tin = [r["input_tokens"] for r in rows if r["nweights"] == 2997 and r["model"] == "sonnet"]
        if tin: print(f"Measured input: {sum(tin)/len(tin):.0f} tokens per ~3,000-weight prompt "
                      f"(about {(sum(tin)/len(tin)-400)/2997:.1f} tokens per weight)")
    round2_gate(rows)
    print("\nModel IDs returned:", sorted({r['model_id'] for r in rows}))

def mcnemar_one_sided(b, c):
    """Exact one-sided McNemar: P(X >= b) for X ~ Binomial(b + c, 0.5)."""
    from math import comb
    n = b + c
    return 1.0 if n == 0 else sum(comb(n, i) for i in range(b, n + 1)) / 2 ** n

def round2_gate(rows):
    """Pre-registered rule (written Nov 4, 2026, before round 2 was run):
    Pool every ~3,000-weight network shown to Sonnet at medium effort with a 6,000-token cap
    (8 from round 1 + 16 from round 2 = 24 networks, each shown as original and as broken).
    GO if ALL hold: (1) originals correct >= 60%; (2) originals correct minus broken caught >= 25 points;
    (3) one-sided exact McNemar p < 0.05, where b = networks with the original right but the broken version
    missed, and c = networks with the original wrong but the broken version caught.
    'Caught' means the model answered I. Truncated or missing answers count as wrong."""
    main = [r for r in rows if r["run"] in ("sonnet_medium_6k", "sonnet_medium_6k_extra") and r["nweights"] == 2997]
    if not any(r["run"] == "sonnet_medium_6k_extra" for r in main): return
    from collections import defaultdict
    net = defaultdict(dict)
    for r in main: net[r.get("network") or f"{r['func']}_H{r['H']}"][r["version"]] = r   # round-1 rows predate the network field
    full = {k: v for k, v in net.items() if "orig" in v and "flip" in v}
    n = len(full)
    oc = sum(v["orig"]["correct"] for v in full.values()); fc = sum(v["flip"]["correct"] for v in full.values())
    named = sum(v["flip"]["named_original"] for v in full.values())
    b = sum(v["orig"]["correct"] and not v["flip"]["correct"] for v in full.values())
    c = sum((not v["orig"]["correct"]) and v["flip"]["correct"] for v in full.values())
    p = mcnemar_one_sided(b, c); ao, af = oc / n, fc / n
    print(f"\n=== PRE-REGISTERED ROUND-2 GATE ({n} paired ~3,000-weight networks, Sonnet medium, 6k cap) ===")
    print(f"Originals correct: {oc}/{n} ({ao:.0%}); broken caught: {fc}/{n} ({af:.0%}); "
          f"broken named as the original function: {named}/{n}")
    print(f"Pairs: original right + broken missed = {b}; original wrong + broken caught = {c}; one-sided McNemar p = {p:.4f}")
    ok = [ao >= 0.6, ao - af >= 0.25, p < 0.05]
    print(f"1. Originals >= 60%: {'PASS' if ok[0] else 'FAIL'}   2. Gap >= 25 points ({ao-af:+.0%}): {'PASS' if ok[1] else 'FAIL'}   "
          f"3. p < 0.05: {'PASS' if ok[2] else 'FAIL'}")
    print("VERDICT:", "GO" if all(ok) else ("NO-GO: Claude can't read big networks under the cap" if not ok[0]
          else "NO DISSOCIATION: reading works but broken networks are caught about as often (rescope the headline)"))
    hk = [r for r in rows if r["run"] == "haiku_nothink_big"]
    if hk:
        o = [r for r in hk if r["version"] == "orig"]; f = [r for r in hk if r["version"] == "flip"]
        print(f"Haiku, no thinking ('glance' reader): originals {sum(r['correct'] for r in o)}/{len(o)}, "
              f"broken caught {sum(r['correct'] for r in f)}/{len(f)}, broken named as original "
              f"{sum(r['named_original'] for r in f)}/{len(f)}, unanswered {sum(r['answer'] is None for r in hk)}/{len(hk)}")

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true"); ap.add_argument("--count-only", action="store_true")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--round2-only", action="store_true", help="only run the round-2 runs (never re-runs round-1 calls that were skipped)")
    a = ap.parse_args()
    if a.report: report()
    elif a.count_only: count_only()
    else: run(a)
